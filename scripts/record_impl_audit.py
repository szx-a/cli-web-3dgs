"""本轮整体实现审计的结论记录（供文档与后续决策）。

用户反馈："点云质量依旧不高，网络和纹理简直是灾难……为什么优化手段数学上是没问题的
但比没优化差距不大甚至更差，要从整体的实现逻辑检查。"

本脚本把审计得到的**量化证据**汇总成 markdown，供 `docs/03` 追加。三块：
  A. 训练规模与社区差多少（数量级）
  B. λd=1.5 的 3 次重复复核 —— **不显著**（推翻此前的 +0.199）
  C. 致密化判据的结构性错误（本轮最重要发现）
  D. 高斯参数分布的两个病态

用法: python scripts/record_impl_audit.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "03-踩坑记录.md"
MARKER = "### G90."

BODY = """### G90. 【整体实现审计】为什么"数学正确的优化"实测收益很小 —— 找到三个结构性错误
用户的原话："点云质量依旧不是很高，网络和纹理简直是灾难……为什么优化手段数学上
是没问题的但比没优化差距不大甚至更差，要从整体的实现逻辑检查。"
本轮按"整体实现"而非"单个参数"审计，找到三个**结构性**问题（不是调参能解决的）。

#### A. 训练规模与社区差了数量级

| 指标 | 本项目 final-v1 | 社区 3DGS（同规模场景）|
|---|---|---|
| 迭代 | 8,000 | 30,000 |
| `densify_until` | **4,000** | 15,000 |
| 每视图高斯 | **768** | 1,000~5,000 |
| PSNR | **23.23 dB** | 27~31 dB |
| 训练耗时 | **2.99 分钟** | 20~40 分钟 |

⇒ 我们一直在**1/4 的预算**下训练，却拿它和社区结果比。但**单纯加预算也没用**
（见 C：加 4.3 倍高斯，PSNR 反降 0.874 dB）。

#### B. 复核 λd=1.5：**3 次重复后不显著**（推翻我此前的 +0.199 dB）

| 组 | n | 均值 | 标准差 |
|---|---|---|---|
| λd=0 | 3 | 23.719 | 0.027 |
| λd=1.5 | 3 | 23.745 | 0.070 |

Δ = **+0.026 dB**，95% CI = **[−0.111, +0.164] ⇒ 不显著**。
此前那个 "+0.199 dB（显著）"是**单次 20000 迭代**的结果，属于运气。
**教训**：我自己定了"先测噪声底、要 3 次重复"的纪律，却没有对这项执行 ——
纪律只对"别人提的方案"执行、对"自己发现的方案"不执行，是典型的双标。

#### C. 【核心】致密化判据用错了空间：3D 世界梯度 vs 官方 2D 屏幕梯度

**官方 3DGS / gsplat `DefaultStrategy`**：
```python
grads = meta["means2d"].grad            # [C,N,2] 屏幕空间梯度
grads[..., 0] *= width / 2 * n_cameras  # 换算到 [-1,1] 屏幕空间
grads = grads.norm(dim=-1) / count.clamp_min(1)   # 除以被看到次数
densify if grads > grow_grad2d
```
**本项目旧实现**：`means.grad.norm(dim=-1) > 2e-4`（3D **世界空间**梯度）

实测差异（`scripts/probe_densify_criterion.py`，final-v1，40 视角）：

| 判据 | p50 | p90 | 超阈值比例 |
|---|---|---|---|
| 3D 梯度 | 1.60e-04 | 3.05e-03 | **2.6%** |
| 官方 2D | 3.55e-06 | 6.89e-05 | **0.2%** |
| **两者交集** | | | **IoU = 0.065** |

⇒ **量纲差 ~45 倍**（所以那个 "2e-4 实测校准值"根本不是官方阈值，只是碰巧能用）；
更严重的是**选出的高斯几乎完全不同**（IoU 0.065）。

**后果已验证**：`densify_until=15000`

| 配置 | PSNR | 高斯数 | 近透明高斯占比 |
|---|---|---|---|
| 4000 | **24.356** | 135,708 | 21.2% |
| 15000 | 23.482（**−0.874**）| **587,620**（4.3×）| **36.8%** |

**3D 梯度大的地方 = 世界空间里位置敏感，但屏幕上看不出差别** ⇒
加密在那里**不产生细节，只产生"雾"**。这就是"高斯多了、质量没上去"的机制。

**修法**：新增 `train.densify_criterion`，默认 `grad2d`（官方口径），
旧行为 `grad3d` 保留以便 A/B。**只改判据来源，不动 duplicate/split/prune 的其余逻辑**
（那部分拆一半移植曾失败三次，见 G31）。
单次 A/B：`grad2d` **24.361** vs `grad3d` 24.180（+0.181，高斯数相近）——
**初步有效，但按纪律必须 3 次重复才能定论。**

#### D. 高斯参数分布的两个病态（`scripts/audit_gaussian_stats.py`）

| 作业 | 高斯/视图 | op<0.05 占比 | PSNR |
|---|---|---|---|
| final-v1（4000）| 768 | 26.7% | 23.23 |
| dz4000 | — | 21.2% | **24.356** |
| dz15000 | 3,229 | **36.8%** | 23.482 |

尺度本身正常（p50/场景 = 0.142%，p99/p50 = 7.4）⇒ **不是尺度问题**。
两个病态是：**① 近透明高斯占比 20~37%**（叠加成"雾"⇒ 灰蒙）；
**② 每视图高斯数不足**（细节表达不够）。

#### 结论：三条"整体逻辑"层面的修正方向
1. **判据必须在正确的空间里**（2D 屏幕梯度），否则加密是无效甚至有害的 —— 已修；
2. **半透明浮点需要治理**（`opacity_reg` 默认 0，社区 MCMC/Faster-GS 用 0.01）——
   这解释了"灰蒙"，且与"加密越多越灰"一致；
3. **训练预算**（迭代/致密化窗口）要和判据**配套**：官方是 30k 迭代 + 15k 窗口 +
   2D 判据，三者是一套；只改其中一个不会有效（我此前单独改窗口失败就是证据）。
"""


def main() -> int:
    text = DOC.read_text(encoding="utf-8")
    if MARKER in text:
        print(f"已存在 {MARKER!r}，跳过（幂等）")
        return 0
    DOC.write_text(text.rstrip("\n") + "\n\n" + BODY.strip("\n") + "\n", encoding="utf-8")
    print(f"已追加 G90（{len(BODY.splitlines())} 行）到 {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
